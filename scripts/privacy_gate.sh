#!/bin/sh
# RXScan privacy gate: generic secret/identity pattern scanner.
#
# Scans git-tracked files for values that must never ship: contact details,
# operator home paths, private keys, bearer tokens, cloud/forge tokens,
# non-reserved public IPs, non-reserved phone numbers, agent/model attribution
# trailers, and .env-style credential assignments.
#
# This script is intentionally GENERIC and safe to commit: it holds no
# project-specific, personal or literal deny terms. A maintainer who wants
# extra literal terms (name, handle, hostname) keeps them in the untracked
# `privacy-denylist.local.txt`, which this script loads when present. The
# committed gate is fully effective without it.
#
# It never rewrites files, never prints a matched value (only a short
# non-reversible digest), and never touches git history.
#
# Usage: sh scripts/privacy_gate.sh
#   Prints one line per finding, a summary, and exits 1 when anything hits.

set -eu

ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
cd "$ROOT"

ALLOWLIST="scripts/privacy_gate.allowlist"
DENYLIST="privacy-denylist.local.txt"

# Canonical detector identifiers. `tests/privacy_gate.rs` parses this exact
# list and fails if the Rust gate does not declare the same set, so the two
# implementations cannot silently drift apart.
PATTERN_IDS="email home_path private_key bearer aws_key forge_token coauthor agent_footer env_assignment public_ip phone"

# Reserved / documentation values: acceptable, never reported.
RESERVED_EMAIL_RE='@([A-Za-z0-9-]+\.)*(example\.(test|com|org|net)|invalid|localhost|test)$'
# 0/8 10/8 127/8 169.254/16 172.16/12 192.168/16, 192.0.2/24 198.51.100/24
# 203.0.113/24 documentation, 198.18/15 benchmark, 100.64/10 CGNAT (RFC 6598),
# 1.0.0.0/8 "this network" (RFC 1122), 224/4 multicast, 240/4 reserved.
RESERVED_IP_RE='^(0\.|1\.0\.0\.|10\.|100\.(6[4-9]|[7-9][0-9]|1[01][0-9]|12[0-7])\.|127\.|169\.254\.|172\.(1[6-9]|2[0-9]|3[01])\.|192\.168\.|192\.0\.2\.|198\.1[89]\.|198\.51\.100\.|203\.0\.113\.|22[4-9]\.|23[0-9]\.|24[0-9]\.|255\.)'
# NANP fictitious block is NPA-555-01XX; the token itself is the whole match.
RESERVED_PHONE_RE='^([0-9]{3}[ .-])?555[ .-]01[0-9]{2}$'

WORK="$(mktemp -d "${TMPDIR:-/tmp}/rxscan-privacy-gate.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
FINDINGS="$WORK/findings"

# Files git tracks, newline separated (paths in this repository never
# contain newlines; git quotes such paths rather than emitting them raw).
git ls-files > "$WORK/tracked"

# allowed <id> <path> <value-digest> -> 0 when a reviewed exception covers it.
#
# Exceptions are keyed on the *value digest*, never on the path alone, so
# clearing one known fixture never blinds the detector to a different value
# appearing in that same file later. Use `*` as the digest only for values
# that are structural (for example a forbidden-path needle list, where the
# literal is the detector's own vocabulary rather than data).
allowed() {
  [ -f "$ALLOWLIST" ] || return 1
  awk -F'|' -v id="$1" -v path="$2" -v dg="$3" '
    /^[[:space:]]*#/ || NF < 3 { next }
    $1 != id { next }
    {
      p = $2
      n = length(p)
      ok = 0
      if (p == path) { ok = 1 }
      else if (substr(p, n, 1) == "/" && index(path, substr(p, 1, n - 1)) == 1) { ok = 1 }
      if (ok && ($3 == "*" || index($3, dg) == 1)) { found = 1 }
    }
    END { exit (found ? 0 : 1) }
  ' "$ALLOWLIST"
}

# digest <value> -> first 16 hex chars of its SHA-256, via whichever
# implementation this platform provides. Used so a maintainer can confirm two
# findings are the same value without the value ever being printed.
digest() {
  if command -v sha256sum >/dev/null 2>&1; then
    printf '%s' "$1" | sha256sum | cut -c1-16
  elif command -v shasum >/dev/null 2>&1; then
    printf '%s' "$1" | shasum -a 256 | cut -c1-16
  else
    printf '%s' "$1" | cksum | cut -c1-16
  fi
}

# emit <id> <path> <line> <value>  (never prints <value> itself)
emit() {
  printf '%s %s:%s sha256:%s\n' "$1" "$2" "$3" "$(digest "$4")" >> "$FINDINGS"
}

: > "$FINDINGS"

for id in $PATTERN_IDS; do
  case "$id" in
    email)          re='[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}' ;;
    home_path)      re='(/home/[A-Za-z0-9._-]+|/Users/[A-Za-z0-9._-]+|[A-Za-z]:\\Users\\)' ;;
    private_key)    re='-----BEGIN [A-Z ]*PRIVATE KEY-----' ;;
    bearer)         re='[Bb]earer [A-Za-z0-9._~+/=-]{20,}' ;;
    aws_key)        re='AKIA[0-9A-Z]{16}' ;;
    forge_token)    re='(ghp_[A-Za-z0-9]{36}|github_pat_[A-Za-z0-9_]{20,}|glpat-[A-Za-z0-9_-]{20,}|xox[baprs]-[A-Za-z0-9-]{10,}|sk-[A-Za-z0-9]{20,})' ;;
    coauthor)       re='Co-Authored-By:' ;;
    agent_footer)   re='(Generated with|Generated by|Co-Generated-By|Written by (an? )?(AI|LLM))' ;;
    env_assignment) re='^[[:space:]]*(export[[:space:]]+)?([A-Za-z_][A-Za-z0-9_]*_)?(SECRET|TOKEN|PASSWORD|PASSWD|APIKEY|API_KEY|ACCESS_KEY|PRIVATE_KEY|CREDENTIAL)[A-Za-z0-9_]*=' ;;
    public_ip)      re='(25[0-5]|2[0-4][0-9]|1[0-9][0-9]|[1-9]?[0-9])(\.(25[0-5]|2[0-4][0-9]|1[0-9][0-9]|[1-9]?[0-9])){3}' ;;
    phone)          re='[0-9]{3}[ .-][0-9]{3}[ .-][0-9]{4}' ;;
    *)              re='$^' ;;
  esac

  while IFS= read -r file; do
    [ -f "$file" ] || continue
    case "$file" in
      *.png|*.jpg|*.jpeg|*.gif|*.webp|*.pdf|*.zip|*.gz|*.woff|*.woff2|*.ico) continue ;;
    esac
    grep -IEn -e "$re" "$file" 2>/dev/null > "$WORK/raw" || true
    [ -s "$WORK/raw" ] || continue
    while IFS= read -r line; do
      ln="${line%%:*}"
      rest="${line#*:}"
      # Extract the actual matched token(s) on this line, not the whole line,
      # so reserved-value rules are tested against the value itself.
      printf '%s\n' "$rest" | grep -Eo -e "$re" 2>/dev/null \
        | sed -e 's/^[Bb]earer //' -e 's/^[[:space:]]*//' \
              -e 's/^export[[:space:]]*//' -e 's/=$//' > "$WORK/tokens" || true
      [ -s "$WORK/tokens" ] || continue
      hit=0
      offender=""
      while IFS= read -r tok; do
        [ -n "$tok" ] || continue
        case "$id" in
          email)
            printf '%s' "$tok" | grep -Eq "$RESERVED_EMAIL_RE" && continue
            ;;
          public_ip)
            printf '%s' "$tok" | grep -Eq "$RESERVED_IP_RE" && continue
            ;;
          phone)
            printf '%s' "$tok" | grep -Eq "$RESERVED_PHONE_RE" && continue
            ;;
        esac
        if allowed "$id" "$file" "$(digest "$tok")"; then
          continue
        fi
        offender="$tok"
        hit=1
        break
      done < "$WORK/tokens"
      [ "$hit" -eq 1 ] || continue
      emit "$id" "$file" "$ln" "$offender"
    done < "$WORK/raw"
  done < "$WORK/tracked"
done

# Optional maintainer-owned literal terms. Never committed.
if [ -f "$DENYLIST" ]; then
  while IFS= read -r term || [ -n "$term" ]; do
    case "$term" in ''|\#*) continue ;; esac
    while IFS= read -r file; do
      [ -f "$file" ] || continue
      case "$file" in
        *.png|*.jpg|*.jpeg|*.gif|*.webp|*.pdf|*.zip|*.gz|*.woff|*.woff2|*.ico) continue ;;
      esac
      if grep -Iq -F "$term" "$file" 2>/dev/null; then
        emit denylist "$file" 1 "$term"
      fi
    done < "$WORK/tracked"
  done < "$DENYLIST"
fi

sort -u "$FINDINGS" > "$WORK/final"
COUNT=$(wc -l < "$WORK/final" | tr -d ' ')
SCANNED=$(wc -l < "$WORK/tracked" | tr -d ' ')

if [ "$COUNT" -gt 0 ]; then
  echo "privacy-gate: FAIL — $COUNT finding(s) across $SCANNED tracked file(s)" >&2
  echo "Values are never printed; each line carries a short digest only." >&2
  echo "Reviewed exceptions belong in $ALLOWLIST as '<id>|<path>|<reason>'." >&2
  cat "$WORK/final" >&2
  exit 1
fi

echo "privacy-gate: PASS — 0 findings across $SCANNED tracked file(s)"